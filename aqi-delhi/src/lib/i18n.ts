export type Key = keyof (typeof D)["en"];

export const t = (lang: Lang, key: Key): string => D[lang][key] ?? D.en[key];

export const cat = (lang: Lang, band: { k: string; hi: string }) =>
  lang === "hi" ? band.hi : band.k;

/** Build an in-site href for a language. */
export const href = (lang: Lang, path = "") => {
  const p = path.replace(/^\/+/, "");
  const base = lang === "hi" ? "/hi" : "";
  return `${base}/${p}`.replace(/\/+$/, "") || "/";
};
